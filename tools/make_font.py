#!/usr/bin/env python3
"""Generate the firmware's Fredoka bitmap fonts (ASCII 32..126)."""
import pathlib
import sys

from PIL import ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools" / "fredoka_variable.ttf"
OUT = ROOT / "firmware" / "include" / "fredoka_font.h"
SIZES = [(12, "Fredoka12"), (16, "Fredoka16"), (20, "Fredoka20"), (28, "Fredoka28"), (44, "Fredoka44")]


def main() -> None:
    lines = [
        "// Fredoka (SIL Open Font License 1.1) converted to LovyanGFX GFX fonts.",
        "// Generated by tools/make_font.py from fredoka_variable.ttf.",
        "#pragma once",
        "#include <LovyanGFX.hpp>",
        "",
    ]
    for pt, name in SIZES:
        font = ImageFont.truetype(str(SOURCE), pt)
        try:
            font.set_variation_by_axes([700.0, 100.0])
        except Exception:
            pass
        ascent, descent = font.getmetrics()
        y_advance = ascent + descent
        bitmaps, glyphs = [], []
        offset = 0
        for code in range(32, 127):
            ch = chr(code)
            bbox = font.getbbox(ch)
            adv = int(round(font.getlength(ch)))
            if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
                glyphs.append((offset, 0, 0, adv, 0, 0))
                continue
            w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
            x_off, y_off = bbox[0], bbox[1] - ascent
            mask = font.getmask(ch)
            cur = bits = 0
            char_bytes = []
            for y in range(h):
                for x in range(w):
                    val = 1 if mask.getpixel((x, y)) > 80 else 0
                    cur = (cur << 1) | val
                    bits += 1
                    if bits == 8:
                        char_bytes.append(cur)
                        cur = 0
                        bits = 0
            if bits:
                char_bytes.append(cur << (8 - bits))
            glyphs.append((offset, w, h, adv, x_off, y_off))
            bitmaps.extend(char_bytes)
            offset += len(char_bytes)
        lines.append(f"const uint8_t {name}Bitmaps[] PROGMEM = {{")
        for i in range(0, len(bitmaps), 16):
            lines.append("  " + ", ".join(f"0x{b:02X}" for b in bitmaps[i:i + 16]) + ",")
        lines.append("};")
        lines.append(f"const lgfx::GFXglyph {name}Glyphs[] PROGMEM = {{")
        for off, w, h, adv, xo, yo in glyphs:
            lines.append(f"  {{ {off:6d}, {w:3d}, {h:3d}, {adv:3d}, {xo:3d}, {yo:3d} }},")
        lines.append("};")
        lines.append(f"const lgfx::GFXfont {name} = {{")
        lines.append(f"  (uint8_t*){name}Bitmaps, (lgfx::GFXglyph*){name}Glyphs, 32, 126, {y_advance}")
        lines.append("};")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
