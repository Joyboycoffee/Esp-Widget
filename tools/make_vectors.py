#!/usr/bin/env python3
"""Generate shared protocol test vectors for the firmware and Android tests."""
import json
import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parent.parent
VECTORS = ROOT / "protocol" / "vectors.json"
HEADER = ROOT / "firmware" / "test" / "vectors_generated.h"


def crc16(data: bytes) -> int:
    crc = 0xFFFF
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def frame(msg_type: int, seq: int, payload: bytes = b"") -> bytes:
    header = struct.pack("<2sBBBHH", b"EW", 2, msg_type, 0, seq, len(payload))
    body = header[2:] + payload
    return header + payload + struct.pack("<H", crc16(body))


def fragments(raw: bytes, chunk: int, frame_id: int) -> list[bytes]:
    count = (len(raw) + chunk - 1) // chunk
    out = []
    for i in range(count):
        part = raw[i * chunk:(i + 1) * chunk]
        out.append(bytes([0xF1, frame_id, i, count, 0]) + part)
    return out


def main() -> None:
    hello = struct.pack("<16sBBBBHHHBB3s", b"ESP-WIDGET-A1B2", 1, 0, 0, 1, 1024, 240, 240, 5, 0, b"\0\0\0")
    time_payload = struct.pack("<IhBB", 0x66F0A2B0, 330, 0, 0)
    settings = struct.pack("<BBBBBBB", 180, 60, 3, 0b0011, 0, 0, 0)
    ping = frame(0x30, 0x1234)
    time_frame = frame(0x10, 0x0042, time_payload)
    settings_frame = frame(0x21, 0x0007, settings)
    hello_frame = frame(0x01, 0x0001, hello)
    vectors = {
        "protocol": 2,
        "crc": {"input": "313233343536373839", "value": 0x29B1},
        "frames": [
            {"name": "ping", "hex": ping.hex(), "type": 0x30, "seq": 0x1234, "payload": ""},
            {"name": "time", "hex": time_frame.hex(), "type": 0x10, "seq": 0x0042, "payload": time_payload.hex()},
            {"name": "settings", "hex": settings_frame.hex(), "type": 0x21, "seq": 0x0007, "payload": settings.hex()},
            {"name": "hello", "hex": hello_frame.hex(), "type": 0x01, "seq": 0x0001, "payload": hello.hex()},
        ],
        "fragmentation": {
            "frame": time_frame.hex(),
            "chunk": 6,
            "frame_id": 9,
            "chunks": [c.hex() for c in fragments(time_frame, 6, 9)],
        },
    }
    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    VECTORS.write_text(json.dumps(vectors, indent=2) + "\n", encoding="utf-8")

    HEADER.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tools/make_vectors.py. Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace espw_test {",
    ]
    for i, item in enumerate(vectors["frames"]):
        lines.append(f"static const uint8_t frame_{i}[] = {{{', '.join('0x%02X' % b for b in bytes.fromhex(item['hex']))}}};")
    lines.append(f"static const uint8_t time_frame[] = {{{', '.join('0x%02X' % b for b in bytes.fromhex(vectors['fragmentation']['frame']))}}};")
    lines.append("static const uint8_t time_chunks[][32] = {")
    for chunk in vectors["fragmentation"]["chunks"]:
        data = bytes.fromhex(chunk)
        lines.append(f"  {{{', '.join('0x%02X' % b for b in data)}}},")
    lines.append("};")
    lines.append(f"static const uint8_t time_chunk_lengths[] = {{{', '.join(str(len(bytes.fromhex(c))) for c in vectors['fragmentation']['chunks'])}}};")
    lines.append(f"static const uint8_t time_chunk_count = {len(vectors['fragmentation']['chunks'])};")
    lines.append("}  // namespace espw_test")
    HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {VECTORS} and {HEADER}")


if __name__ == "__main__":
    main()
